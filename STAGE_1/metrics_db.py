STMT = {
    "income": re.compile(r"statements? of (?:consolidated )?(?:operations|income|earnings)|income statements?|"
                         r"consolidated results of operations|statements? of comprehensive (?:income|loss)", re.I),
    "balance": re.compile(r"balance sheets?|statements? of financial position|financial condition", re.I),
    "cashflow": re.compile(r"statements? of (?:consolidated )?cash flows?|cash flows? statements?", re.I),
}
COMPREHENSIVE = re.compile(r"comprehensive", re.I)
TOTAL_LSE = re.compile(r"^total liabilities (?:and |redeemable )?.*equity|^total liabilities and (?:shareholders|"
                       r"stockholders|shareowners)", re.I)
SIDE = re.compile(r"noncontrolling|non controlling|minority|redeemable|preferred")
TOL = 0.001          # 0.1% ya 1 unit tak farq = same number (rounding); is se zyada = mismatch

SCHEMA = """
DROP TABLE IF EXISTS metrics;
DROP TABLE IF EXISTS checks;
CREATE TABLE metrics(
    company TEXT, fiscal_year INTEGER, metric TEXT, value REAL, value_text TEXT, unit TEXT, unit_guess INTEGER,
    filing_year INTEGER, file_name TEXT, page TEXT, statement_title TEXT, row_label TEXT, status TEXT, note TEXT,
    PRIMARY KEY(company, fiscal_year, metric));
CREATE TABLE checks(
    company TEXT, fiscal_year INTEGER, metric TEXT, check_name TEXT, ok INTEGER, detail TEXT);
CREATE INDEX ix_m ON metrics(company, metric);
"""


def norm(s):
    return re.sub(r"\s+", " ", re.sub(r"[^a-z0-9%&]+", " ", (s or "").lower())).strip()


def close(a, b):
    if a is None or b is None:
        return False
    a, b = abs(a), abs(b)
    return a == b or abs(a - b) <= max(1.0 if max(a, b) >= 1000 else 0.0, TOL * max(a, b))


def same_value(a, b):
    """Same number? -> (ok, note). Company kabhi report ka unit badal deti hai (Workday: thousands -> millions),
    is liye 1000 ka farq bhi 'same' (note ke saath)."""
    if close(a, b):
        return True, ""
    for k in (1000.0, 1000000.0):
        if a is not None and b is not None and (close(a, b * k) or close(a * k, b)):
            return True, "unit badla (x1000)"
    return False, ""


def match_rank(rn, names, metric):
    """Row ka naam metric se kitna milta hai: (0 exact / 1 shuru / None), aur synonym ki jagah."""
    if SIDE.search(rn) and metric in ("net_income", "equity"):
        return None
    for k, nm in enumerate(names):
        if rn == nm:
            return (0, k)
    for k, nm in enumerate(names):
        if rn.startswith(nm + " "):
            if metric == "revenue" and re.search(r"\b(cost|costs|expense|expenses|other income|deferred)\b", rn):
                continue
            if metric == "cash" and re.search(r"\b(restricted|end of|beginning of)\b", rn):
                continue
            if metric == "total_liabilities" and "equity" in rn:        # "total liabilities and equity" alag cheez
                continue
            return (1, k)
    return None


def candidates(con, metric):
    """Ek metric ki saari mumkin rows (sahi statement, number, % nahi)."""
    st, names = METRICS[metric]
    rx = STMT[st]
    likes = " OR ".join(["f.row_norm = ?"] * len(names) + ["f.row_norm LIKE ?"] * len(names))
    args = names + [n + " %" for n in names]
    rows = con.execute(
        f"SELECT t.company, t.year, t.file_name, t.pages, t.title, t.section, t.unit, t.unit_src, f.row_label, "
        f"f.row_norm, f.col_year, f.value_text, f.value_num FROM facts f JOIN tables t ON t.id = f.table_id "
        f"WHERE f.value_num IS NOT NULL AND f.pct = 0 AND f.col_year IS NOT NULL AND ({likes})", args).fetchall()
    out = []
    for r in rows:
        title_sec = f"{r[4]} {r[5]}"
        if not rx.search(title_sec):
            continue
        if st == "income" and COMPREHENSIVE.search(r[4] or "") and metric != "net_income":
            continue
        rank = match_rank(r[9], names, metric)
        if rank is None:
            continue
        if metric == "eps_diluted" and not (abs(r[12]) < 100 and ("." in r[11])):
            continue                                       # "Diluted" shares ki ginti (jaise 489.4 million), EPS nahi
        if metric != "eps_diluted" and r[9] == "diluted":
            continue
        out.append({"company": r[0], "filing_year": r[1], "file_name": r[2], "page": r[3], "title": r[4],
                    "unit": r[6], "unit_guess": int(r[7] == "document ka aam unit"), "row_label": r[8],
                    "col_year": r[10], "value_text": r[11], "value": r[12], "rank": rank,
                    "comprehensive": int(bool(COMPREHENSIVE.search(r[4] or "")))})
    return out


def best(cands):
    """Behtar row: exact naam > shuru; pehla synonym; asal statement (comprehensive income nahi); pehla page."""
    return sorted(cands, key=lambda c: (c["rank"], c["comprehensive"], c["page"] or ""))[0]


def build(db_path):
    t0 = time.time()
    con = sqlite3.connect(db_path)
    if not con.execute("SELECT name FROM sqlite_master WHERE name='facts'").fetchone():
        raise SystemExit("Raw layer nahi mili. Pehle:  python STAGE_1/facts_db.py build")
    con.executescript(SCHEMA)

    # har filing ka apna fiscal year = us ki statements ka sab se naya column-saal
    own_fy = {}
    for comp, fy_file, fname, cy in con.execute(
            "SELECT t.company, t.year, t.file_name, MAX(f.col_year) FROM facts f JOIN tables t ON t.id = f.table_id "
            "WHERE t.statement = 1 AND f.col_year BETWEEN 1990 AND 2100 AND f.col_year <= t.year + 1 "
            "GROUP BY t.company, t.year, t.file_name"):
        own_fy[(comp, fname)] = cy

    # filing jis ka apna saal FY+1 hai (pichle saal ka column check ke liye)
    by_comp_fy = {(c, fy): fname for (c, fname), fy in own_fy.items()}

    picked = {}                      # (company, fy, metric) -> row
    later = defaultdict(list)        # (company, fy, metric) -> agli filing ki rows
    for metric in METRICS:
        groups = defaultdict(list)
        for c in candidates(con, metric):
            fy = own_fy.get((c["company"], c["file_name"]))
            if fy is None:
                continue
            if c["col_year"] == fy:
                groups[("own", c["company"], fy)].append(c)
            elif c["col_year"] == fy - 1 and by_comp_fy.get((c["company"], fy)) == c["file_name"]:
                groups[("next", c["company"], fy - 1)].append(c)
        for (kind, comp, fy), cs in groups.items():
            if kind == "own":
                picked[(comp, fy, metric)] = best(cs)
            else:
                later[(comp, fy, metric)].append(best(cs))

    # checks
    checks = []
    status = {}
    for key, row in picked.items():
        comp, fy, metric = key
        results = []
        nxt = later.get(key)
        if nxt:
            n = nxt[0]
            ok, note = same_value(row["value"], n["value"])
            results.append(ok)
            checks.append((comp, fy, metric, "cross_year", int(ok),
                           f"{row['value_text']} (filing {row['filing_year']}) vs {n['value_text']} "
                           f"(filing {n['filing_year']}, p{n['page']})" + (f" -- {note}" if note else
                           "" if ok else " -- restatement ya parsing; XBRL se tay hoga")))
        status[key] = results

    # balance sheet: total assets = total liabilities and equity (usi filing, usi column)
    lse = defaultdict(list)
    for r in con.execute(
            "SELECT t.company, t.file_name, f.col_year, f.row_norm, f.value_num, f.value_text FROM facts f "
            "JOIN tables t ON t.id = f.table_id WHERE f.value_num IS NOT NULL AND f.row_norm LIKE 'total liabilities%'"):
        if TOTAL_LSE.search(r[3]):
            lse[(r[0], r[1], r[2])].append(r)
    for (comp, fy, metric), row in picked.items():
        if metric != "total_assets":
            continue
        cands = lse.get((comp, row["file_name"], fy))
        if not cands:
            continue
        ok = any(close(row["value"], c[4]) for c in cands)
        checks.append((comp, fy, "total_assets", "balance_sheet", int(ok),
                       f"total assets {row['value_text']} vs total liabilities and equity {cands[0][5]}"))
        status.setdefault((comp, fy, "total_assets"), []).append(ok)

    rows = []
    for key, row in picked.items():
        res = status.get(key, [])
        st = "conflict" if False in res else "verified" if res else "unchecked"
        rows.append((key[0], key[1], key[2], row["value"], row["value_text"],
                     None if key[2] == "eps_diluted" else row["unit"], row["unit_guess"], row["filing_year"],
                     row["file_name"], row["page"], row["title"], row["row_label"], st, None))
    con.executemany("INSERT OR REPLACE INTO metrics VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?)", rows)
    con.executemany("INSERT INTO checks VALUES (?,?,?,?,?,?)", checks)
    con.commit()
    n = len(rows)
    v = sum(1 for r in rows if r[12] == "verified")
    c = sum(1 for r in rows if r[12] == "conflict")
    print(f"Curated layer ban gayi ({time.time() - t0:.0f} sec): {n:,} metric rows "
          f"(verified {v:,}, conflict {c:,}, unchecked {n - v - c:,}), checks {len(checks):,}")
    con.close()


def resolve_company(con, name):
    comps = [r[0] for r in con.execute("SELECT DISTINCT company FROM metrics")]
    hit = [c for c in comps if norm(name) == norm(c)] or [c for c in comps if norm(name) in norm(c)]
    return hit[0] if hit else None


def resolve_metric(name):
    n = norm(name).replace(" ", "_")
    if n in METRICS:
        return n
    return ALIASES.get(norm(name))


def show(db_path, company, metric, year=None):
    con = sqlite3.connect(db_path)
    comp = resolve_company(con, company)
    m = resolve_metric(metric)
    if not comp or not m:
        print(f"Nahi mila: company={company!r} ({comp}) metric={metric!r} ({m}). Metrics: {', '.join(METRICS)}")
        return
    where, args = "company=? AND metric=?", [comp, m]
    if year:
        where, args = where + " AND fiscal_year=?", args + [year]
    rows = con.execute("SELECT fiscal_year, value_text, unit, unit_guess, page, statement_title, row_label, status, "
                       f"filing_year FROM metrics WHERE {where} ORDER BY fiscal_year", args).fetchall()
    if not rows:
        print(f"{comp} {LABELS[m]}: koi row nahi" + (f" (FY{year})" if year else ""))
        return
    print(f"{comp} -- {LABELS[m]}")
    for fy, vt, unit, ug, page, title, label, st, filing in rows:
        u = (f" {unit}" + (" (andaza)" if ug else "")) if unit else ""
        mark = {"verified": "✓", "conflict": "!", "unchecked": " "}[st]
        print(f"  FY{fy}  {vt:>14}{u:<20} {mark} {st:<9}  p{page}  {(title or '')[:45]}  [{label}]  (filing {filing})")
    for fy, check, detail in con.execute(
            f"SELECT fiscal_year, check_name, detail FROM checks WHERE {where} AND ok=0 ORDER BY fiscal_year", args):
        print(f"  ! FY{fy} {check}: {detail}")


def report(db_path):
    con = sqlite3.connect(db_path)
    comps = con.execute("SELECT COUNT(DISTINCT company) FROM metrics").fetchone()[0]
    filings = con.execute("SELECT COUNT(DISTINCT company || file_name) FROM metrics").fetchone()[0]
    print(f"\nCURATED METRICS -- {comps} companies, {filings} filings\n")
    print(f"  {'metric':<22}{'filings':>8}{'coverage':>10}{'verified':>10}{'conflict':>10}{'unchecked':>11}")
    for m in METRICS:
        n, v, c = con.execute("SELECT COUNT(*), SUM(status='verified'), SUM(status='conflict') FROM metrics "
                              "WHERE metric=?", (m,)).fetchone()
        v, c = v or 0, c or 0
        cov = 100 * n / filings if filings else 0
        print(f"  {LABELS[m]:<22}{n:>8}{cov:>9.1f}%{v:>10}{c:>10}{n - v - c:>11}")
    tot = con.execute("SELECT COUNT(*), SUM(status='verified'), SUM(status='conflict') FROM metrics").fetchone()
    print(f"  {'KUL':<22}{tot[0]:>8}{'':>10}{tot[1] or 0:>10}{tot[2] or 0:>10}{tot[0] - (tot[1] or 0) - (tot[2] or 0):>11}")
    print("\n  Checks:")
    for name, n, ok in con.execute("SELECT check_name, COUNT(*), SUM(ok) FROM checks GROUP BY check_name"):
        print(f"    {name:<15} {ok}/{n} pass ({100 * ok / n:.1f}%)")
    bad = con.execute("SELECT company, fiscal_year, metric, check_name, detail FROM checks WHERE ok=0 "
                      "ORDER BY company, fiscal_year LIMIT 15").fetchall()
    if bad:
        print("\n  Kuch fail checks (pehle 15):")
        for b in bad:
            print(f"    {b[0]} FY{b[1]} {b[2]} {b[3]}: {b[4][:110]}")
    print()


def main():
    ap = argparse.ArgumentParser(description="Curated financial metrics (12) + quality checks")
    ap.add_argument("--db", default="STAGE_1/facts.db")
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("build")
    s = sub.add_parser("show")
    s.add_argument("company")
    s.add_argument("metric")
    s.add_argument("year", nargs="?", type=int)
    sub.add_parser("report")
    a = ap.parse_args()
    if not Path(a.db).exists():
        raise SystemExit(f"Database nahi mila: {a.db}. Pehle:  python STAGE_1/facts_db.py build")
    if a.cmd == "build":
        build(a.db)
    elif a.cmd == "show":
        show(a.db, a.company, a.metric, a.year)
    else:
        report(a.db)


if __name__ == "__main__":
    main()