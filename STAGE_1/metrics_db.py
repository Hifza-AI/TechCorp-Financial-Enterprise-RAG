"""
metrics_db.py  -  SQL track ki CURATED layer: raw facts (facts_db.py) se 12 pakke financial metrics + quality checks.

Layers (data engineering ka "medallion" tareeqa):
    raw      facts.db -> tables / facts       har table ka har cell (~1M rows), jaisa PDF mein tha
    curated  facts.db -> metrics / checks     har company + fiscal year + metric ki EK row, jaanch ke saath

Banao:     python STAGE_1/metrics_db.py build
Dekho:     python STAGE_1/metrics_db.py show Nike revenue            (saare saal)
           python STAGE_1/metrics_db.py show Apple net_income 2023
Hisaab:    python STAGE_1/metrics_db.py report                      (coverage + checks, report ke liye)

Har filing ka "apna" fiscal year = us ki financial statements ka sab se naya column. Metric wahin se liya jata hai
(Home Depot ki file 2018 = FY2017 bhi khud theek ho jata hai). Agli filing mein wahi saal "pichle saal" ke column
mein dobara aata hai -> dono milao (cross-year check). Balance sheet: Total assets = Total liabilities and equity.

status:  verified    kam az kam ek check pass, koi fail nahi
         conflict    koi check fail: ya to company ne baad mein number badla (restatement -- jaise naya accounting
                     rule ASC 606, ya business alag karna), ya parsing ki ghalti. SEC XBRL se tay hota hai.
         unchecked   koi check mumkin nahi (agli filing hamare paas nahi, aur balance check is metric par nahi)
"""
